#!/usr/bin/env python3
"""Offline, read-only follower replay runner. No RPC, wallet, or signer."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import sys

from arz.multi_edge.follower_replay import Decision, Episode, Quote, replay


def from_document(document: dict) -> tuple[list[Episode], list[Quote]]:
    if type(document) is not dict or document.get('schema_version') != 1:
        raise ValueError('schema_version=1 required')
    if document.get('data_class') not in ('SYNTHETIC', 'HISTORICAL_UNVERIFIED'):
        raise ValueError('Explicit non-qualifying data_class required')
    if type(document.get('episodes')) is not list or type(document.get('quotes')) is not list:
        raise ValueError('episodes and quotes must be lists')
    episodes = []
    for row in document['episodes']:
        if type(row) is not dict:
            raise ValueError('Episode must be object')
        episodes.append(Episode(episode_id=row['episode_id'],
                                entry=Decision(**row['entry']), exit=Decision(**row['exit']),
                                independent_clusters=tuple(row['independent_clusters'])))
    quotes = [Quote(**row) for row in document['quotes']]
    return episodes, quotes


def run_bytes(raw: bytes, *, delays: tuple[int, ...] = (3, 10, 30, 60, 120)) -> dict:
    document = json.loads(raw.decode('utf-8'))
    episodes, quotes = from_document(document)
    if not delays or any(type(d) is not int or d < 0 for d in delays) or len(set(delays)) != len(delays):
        raise ValueError('Unique nonnegative delays required')
    runs = {str(delay): replay(episodes, quotes, follower_delay_s=delay) for delay in delays}
    return {'schema_version': 1, 'input_sha256': hashlib.sha256(raw).hexdigest(),
            'data_class': document['data_class'], 'input_episodes': len(episodes),
            'input_quotes': len(quotes), 'live_trading': 'DISABLED',
            'financial_decision': 'NO-GO', 'results_by_delay_s': runs,
            'limitations': ['Not independent evidence of quote accuracy or live fills',
                            'Episodes are supplied, not generated by H1 strategy',
                            'No overlapping-position cash ledger or daily equity',
                            'Pool/impact stress not modeled; network-only doubling is a diagnostic']}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True, help='Offline JSON input; no network used')
    args = parser.parse_args(argv)
    try:
        report = run_bytes(args.input.read_bytes())
    except (OSError, ValueError, TypeError, KeyError, UnicodeDecodeError) as exc:
        print(f'FAIL_CLOSED: {type(exc).__name__}: {exc}', file=sys.stderr)
        return 2
    print(json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
